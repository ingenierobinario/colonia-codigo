#!/usr/bin/env node
// Regenera TODO el arte de pingüinos del repo: node scripts/penguins/generate.mjs
// Cuerpos y catálogo (packages/ui), copia de la web pública (apps/docs), atlas de terminal, logos, iconos de escritorio y pancarta.
// Sólo necesita sharp, que ya está instalado por apps/docs.
import fs from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { deflateSync } from "node:zlib";
import { appIcon, BRAND, banner, EYE_COLOR, EYES, fileIcon, glyph, penguin, svg } from "./art.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../..");
const r = (p) => path.join(root, p);
const sharp = createRequire(r("apps/docs/package.json"))("sharp");
const palette = JSON.parse(fs.readFileSync(path.join(here, "palette.json"), "utf8"));
const names = Object.keys(palette);
const KINDS = ["none", "tuft", "scarf", "bow", "crest"];
const presetArt = (name) => ({ color: palette[name].color, kind: KINDS[names.indexOf(name) % KINDS.length] });
const write = (p, data) => {
  fs.mkdirSync(path.dirname(r(p)), { recursive: true });
  fs.writeFileSync(r(p), data);
};
const raster = (source, size) => {
  const vb = Number(/viewBox="0 0 (\d+)/.exec(source)[1]);
  // Se dibuja a más resolución y se reduce: bordes limpios también a 16 px.
  return sharp(Buffer.from(source), { density: Math.min(2400, (72 * Math.max(size * 4, 256)) / vb) }).resize(size, size, {
    kernel: "lanczos3",
    fit: "contain",
    background: { r: 0, g: 0, b: 0, alpha: 0 },
  });
};
const png = (source, size) => raster(source, size).png({ compressionLevel: 9 }).toBuffer();

function ico(images) {
  const head = Buffer.alloc(6 + 16 * images.length);
  head.writeUInt16LE(1, 2);
  head.writeUInt16LE(images.length, 4);
  let at = head.length;
  images.forEach(([size, data], i) => {
    const p = 6 + 16 * i;
    head[p] = size >= 256 ? 0 : size;
    head[p + 1] = size >= 256 ? 0 : size;
    head.writeUInt16LE(1, p + 4);
    head.writeUInt16LE(32, p + 6);
    head.writeUInt32LE(data.length, p + 8);
    head.writeUInt32LE(at, p + 12);
    at += data.length;
  });
  return Buffer.concat([head, ...images.map((x) => x[1])]);
}
function icns(entries) {
  const parts = entries.map(([type, data]) => {
    const h = Buffer.alloc(8);
    h.write(type, 0, "latin1");
    h.writeUInt32BE(data.length + 8, 4);
    return Buffer.concat([h, data]);
  });
  const total = parts.reduce((n, b) => n + b.length, 8);
  const h = Buffer.alloc(8);
  h.write("icns", 0, "latin1");
  h.writeUInt32BE(total, 4);
  return Buffer.concat([h, ...parts]);
}

// --- Cuerpos y catálogo
const catalog = [];
const docs = {};
for (const name of names) {
  const body = svg(penguin(presetArt(name)));
  const webp = await raster(body, 128).webp({ quality: 90, alphaQuality: 95 }).toBuffer();
  write(`packages/ui/src/blobs/bodies/${name}.webp`, webp);
  write(`apps/docs/src/assets/blobs/${name}.webp`, webp);
  const rects = EYES.map(
    (e) => `      { x: ${e.x.toFixed(1)}, y: ${e.y.toFixed(1)}, w: ${e.w.toFixed(1)}, h: ${e.h.toFixed(1)}, rx: ${e.rx.toFixed(1)} },`,
  ).join("\n");
  catalog.push(
    `  ${name}: {\n    label: ${JSON.stringify(palette[name].label)},\n    eyeColor: "${EYE_COLOR}",\n    eyes: [\n${rects}\n    ],\n    src: new URL("./bodies/${name}.webp", import.meta.url).href,\n  },`,
  );
  docs[name] = { label: palette[name].label, eyeColor: EYE_COLOR, eyes: EYES };
}
write(
  "packages/ui/src/blobs/catalog.ts",
  `// AUTO-GENERATED by scripts/penguins/generate.mjs — do not edit by hand.
// Bodies are eyeless; eye rects live in the same 256x256 canvas and are drawn on top
// (animated) by <AgentAvatar>. Bodies are files next to this one (bodies/*.webp, copied to dist/bodies): the browser
// fetches and caches each one as an image instead of holding them as base64 in the panel's first script.

export type BlobEye = { x: number; y: number; w: number; h: number; rx: number };
export type BlobPreset = { label: string; eyeColor: string; eyes: BlobEye[]; src: string };

export const BLOB_VIEWBOX = 256;

export const BLOBS = {
${catalog.join("\n")}
} satisfies Record<string, BlobPreset>;

/** Every blob key in the catalog: "menta", "noche", "kiwi", "coral"… */
export type BlobName = keyof typeof BLOBS;
export const BLOB_NAMES = Object.keys(BLOBS) as BlobName[];
`,
);
write("apps/docs/src/data/blobs.json", `${JSON.stringify(docs, null, 2)}\n`);

// --- Atlas de terminal: mismo formato que scripts/export-terminal-blobs.py (que exige Pillow)
const eyesSvg = svg(EYES.map((e) => `<rect x="${e.x}" y="${e.y}" width="${e.w}" height="${e.h}" rx="${e.rx}" fill="${EYE_COLOR}"/>`).join(""));
const eyes = await png(eyesSvg, 128);
const atlas = {};
for (const name of [...names].sort()) {
  const face = await sharp(r(`packages/ui/src/blobs/bodies/${name}.webp`)).ensureAlpha().composite([{ input: eyes }]).png().toBuffer();
  const { data: px } = await sharp(face).raw().toBuffer({ resolveWithObject: true });
  let [x0, y0, x1, y1] = [128, 128, 0, 0];
  for (let y = 0; y < 128; y++)
    for (let x = 0; x < 128; x++)
      if (px[(y * 128 + x) * 4 + 3] > 0) {
        x0 = Math.min(x0, x);
        y0 = Math.min(y0, y);
        x1 = Math.max(x1, x);
        y1 = Math.max(y1, y);
      }
  const box = { left: x0, top: y0, width: x1 - x0 + 1, height: y1 - y0 + 1 };
  const shrink = (input, w, h) => sharp(input).extract(box).resize(w, h, { fit: "fill", kernel: "lanczos3" }).ensureAlpha().raw().toBuffer();
  const full = await shrink(face, 26, 26);
  const half = await shrink(face, 26, 13);
  const mask = await shrink(eyes, 26, 13);
  const rows = [];
  for (let y = 0; y < 13; y++) {
    let row = "";
    for (let x = 0; x < 26; x++) {
      const i = (y * 26 + x) * 4;
      row += half[i + 3] < 90 ? " " : mask[i + 3] > 60 ? "█" : "▒";
    }
    rows.push(row.trimEnd());
  }
  // El acento de la terminal es el color del preset, no la media con la barriga blanca.
  const c = palette[name].color;
  atlas[name] = { rows, color: [1, 3, 5].map((i) => parseInt(c.slice(i, i + 2), 16)), pixels: deflateSync(full, { level: 9 }).toString("base64") };
}
const ascii = JSON.stringify(atlas, null, 2).replace(/[^\x00-\x7f]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, "0")}`);
write("apps/terminal/src/blobs.json", `${ascii}\n`);

// --- Logos
const mark = svg(penguin({ color: BRAND, eyes: true }), 256, "Colonia");
write("apps/web/src/assets/favicon.svg", mark);
write("apps/docs/public/favicon.svg", mark);
write("apps/web/src/assets/logo.png", await png(mark, 64));
write("apps/mobile/assets/logo.png", await png(mark, 64));
write("apps/docs/src/assets/logo.png", await png(mark, 256));
write("apps/docs/public/apple-touch-icon.png", await raster(appIcon({ bleed: true }), 180).flatten({ background: "#0b1014" }).png().toBuffer());

// --- Escritorio
const D = "apps/desktop/assets";
write(`${D}/logo-dock.svg`, appIcon());
write(`${D}/icon.png`, await png(appIcon(), 1024));
write(`${D}/logo-green.svg`, svg(glyph(BRAND), 256, "Colonia"));
write(`${D}/logo-white.svg`, svg(glyph("#fff"), 256, "Colonia"));
const trays = {
  trayTemplate: svg(glyph("#000"), 256, "Colonia"),
  "trayTemplate-attention": svg(glyph("#000", { dot: true }), 256, "Colonia"),
  "tray-white-attention": svg(glyph("#fff", { dot: true }), 256, "Colonia"),
  "tray-color": svg(glyph(BRAND), 256, "Colonia"),
  "tray-color-attention": svg(glyph(BRAND, { dot: true }), 256, "Colonia"),
};
for (const [name, source] of Object.entries(trays)) {
  write(`${D}/${name}.svg`, source);
  write(`${D}/${name}.png`, await png(source, 22));
  write(`${D}/${name}@2x.png`, await png(source, 44));
}
const FILES = [
  ["apxart", "art", "#12B2BD"],
  ["apxapp", "app", "#7228D3"],
  ["apxext", "ext", "#07BB9C"],
];
const ICNS = [["ic11", 32], ["ic12", 64], ["ic07", 128], ["ic08", 256], ["ic13", 256], ["ic09", 512], ["ic14", 512], ["ic10", 1024]];
for (const [ext, type, color] of FILES) {
  const source = fileIcon(type, color);
  write(`${D}/file-${ext}.webp`, await raster(source, 1254).webp({ quality: 90, alphaQuality: 95 }).toBuffer());
  write(`${D}/file-${ext}.png`, await png(source, 512));
  write(`${D}/file-${ext}.ico`, ico(await Promise.all([16, 24, 32, 48, 64, 128, 256].map(async (s) => [s, await png(source, s)]))));
  write(`${D}/file-${ext}.icns`, icns(await Promise.all(ICNS.map(async ([t, s]) => [t, await png(source, s)]))));
}

// --- Pancarta
const row = ["menta", "brasa", "amatista", "cobalto", "coral", "noche", "kiwi", "papa"].map(presetArt);
write("assets/banner.webp", await sharp(Buffer.from(banner(1640, 547, row))).flatten({ background: "#060a0d" }).webp({ quality: 90 }).toBuffer());
console.log(`${names.length} pingüinos generados`);
